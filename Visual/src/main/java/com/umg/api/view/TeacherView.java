private void cleanCampos() {
    txtId.setText("");
    txtDireccion.setText("");
    txtEmail.setText("");
    txtEspecialidad.setText("");
    txtTelefono.setText("");
    ComboEstado.setSelectedItem("");

}

private void updateTable() {
    modelo.setRowCount(0); // Limpiar tabla
    try {
        List<TeacherModel> teachers = service.getaAll(); // <-- Debe devolver List<TeacherModel>
        for (TeacherModel t : teachers) {
            modelo.addRow(new Object[]{
                t.getId(),
                t.getNombre(),
                t.getEmail(),
                t.getTelefono(),
                t.getDireccion(),
                t.getEspecialidad(),
                t.isEstado()? "Activo" : "Inactivo" // Convertimos boolean a texto
            });
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cargar tabla: " + e.getMessage());
    }
}




