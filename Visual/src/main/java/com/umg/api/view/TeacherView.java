    private void fillFieldsFromSelectedRow() {
    int row = tbl.getSelectedRow(); // tu JTable
    if (row != -1) {
        int id = (int) modelo.getValueAt(row, 0);
        txtId.setText(String.valueOf(id));
        txtNombre.setText((String) modelo.getValueAt(row, 1));
        txtEmail.setText((String) modelo.getValueAt(row, 2));
        txtTelefono.setText((String) modelo.getValueAt(row, 3));
        txtDireccion.setText((String) modelo.getValueAt(row, 4));
        txtEspecialidad.setText((String) modelo.getValueAt(row, 5));
        
        // Manejo del estado (boolean a ComboBox)
        boolean estado = false;
        Object estadoObj = modelo.getValueAt(row, 6);
        if (estadoObj instanceof Boolean) {
            estado = (Boolean) estadoObj;
        } else if (estadoObj instanceof String) {
            estado = ((String) estadoObj).equalsIgnoreCase("Activo");
        }
        ComboEstado.setSelectedItem(estado ? "Activo" : "Inactivo");
    }
}

    
