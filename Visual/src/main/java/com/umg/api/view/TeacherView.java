    private void btnCrearMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnCrearMouseClicked
    try {
        TeacherModel teacher = new TeacherModel();
        teacher.setNombre(txtNombre.getText());
        teacher.setEmail(txtEmail.getText());
        teacher.setTelefono(txtTelefono.getText());
        teacher.setDireccion(txtDireccion.getText());
        teacher.setEspecialidad(txtEspecialidad.getText());
        
            String estadoSeleccionado = ComboEstado.getSelectedItem().toString();
            boolean estado = estadoSeleccionado.equalsIgnoreCase("Activo");
            teacher.setEstado(estado);

        TeacherService service = new TeacherService();
        service.create(teacher);

        JOptionPane.showMessageDialog(this, "Profesor agregado correctamente ✅");
        updateTable();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al agregar profesor: " + e.getMessage());
    }

    }//GEN-LAST:event_btnCrearMouseClicked

    private void btnActualizarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnActualizarMouseClicked
        try {
            int id = Integer.parseInt(txtId.getText());
            TeacherModel teacher = new TeacherModel();
            teacher.setNombre(txtNombre.getText());
            teacher.setEmail(txtEmail.getText());
            teacher.setTelefono(txtTelefono.getText());
            teacher.setDireccion(txtDireccion.getText());
            teacher.setEspecialidad(txtEspecialidad.getText());
            teacher.setEstado(ComboEstado.getSelectedItem().toString().equals("Activo"));

            service.update(id, teacher); // Método del Service
            JOptionPane.showMessageDialog(this, "Profesor actualizado correctamente ✅");
            updateTable();
            cleanCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar profesor: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarMouseClicked

    private void btnBuscarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnBuscarMouseClicked
        try {
            int id = Integer.parseInt(txtId.getText().trim());
            modelo.setRowCount(0); // Limpiar tabla

            TeacherModel t = service.getOne(id); // <-- Método en el service que busca por PK
            if (t != null) {
                modelo.addRow(new Object[]{
                    t.getId(),
                    t.getNombre(),
                    t.getEmail(),
                    t.getTelefono(),
                    t.getDireccion(),
                    t.getEspecialidad(),
                    t.isEstado() ? "Activo" : "Inactivo"
                });
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró un profesor con ID " + id);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un ID válido");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al buscar profesor: " + e.getMessage());
        }
    }//GEN-LAST:event_btnBuscarMouseClicked

