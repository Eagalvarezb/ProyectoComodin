    private void btnCrearMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnCrearMouseClicked
    try {
        CursosModel data = new CursosModel();
        data.setTeacherId(Integer.parseInt(txtIdTeacher.getText()));
        data.setNombre(txtNombre.getText());
        data.setCodigo(txtCodigo.getText());
        data.setModalidad(txtMod.getText());
        data.setCredito(Float.parseFloat(txtCredito.getText()));

        CursosService service = new CursosService();
        service.create(data);

        JOptionPane.showMessageDialog(this, "Info agregado correctamente ✅");
        updateTable();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al agregar Info: " + e.getMessage());
    }

    }//GEN-LAST:event_btnCrearMouseClicked

    private void btnActualizarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnActualizarMouseClicked
        try {
            int id = Integer.parseInt(txtId_Curso.getText());
            CursosModel data = new CursosModel();
            data.setTeacherId(Integer.parseInt(txtIdTeacher.getText()));
            data.setNombre(txtNombre.getText());
            data.setCodigo(txtCodigo.getText());
            data.setModalidad(txtMod.getText());
            data.setCredito(Float.parseFloat(txtCredito.getText()));
            
            service.update(id, data); // Método del Service
            JOptionPane.showMessageDialog(this, "Info actualizado correctamente ✅");
            updateTable();
            cleanCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar Info: " + e.getMessage());
        }
    }//GEN-LAST:event_btnActualizarMouseClicked

    private void btnBuscarMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnBuscarMouseClicked
        try {
            int id = Integer.parseInt(txtId_Curso.getText().trim());
            modelo.setRowCount(0); // Limpiar tabla

            CursosModel t = service.getOne(id);
            if (t != null) {
                modelo.addRow(new Object[]{
                    t.getId_curso(),
                    t.getTeacherId(),
                    t.getNombre(),
                    t.getCodigo(),
                    t.getModalidad(),
                    t.getCredito()
                });
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró un Info con ID " + id);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un ID válido");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al buscar Info: " + e.getMessage());
        }
    }//GEN-LAST:event_btnBuscarMouseClicked

