private void cleanCampos() {
    txtId_Curso.setText("");
    txtNombre.setText("");
    txtCodigo.setText("");
    txtIdTeacher.setText("");

}

private void updateTable() {
    modelo.setRowCount(0); // Limpiar tabla
    try {
        List<CursosModel> data = service.getAll();
        for (CursosModel t : data) {
            modelo.addRow(new Object[]{
                t.getId_curso(),
                t.getTeacherId(),
                t.getNombre(),
                t.getCodigo(),
                t.getModalidad(),
                t.getCredito()
            });
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cargar tabla: " + e.getMessage());
    }
}




